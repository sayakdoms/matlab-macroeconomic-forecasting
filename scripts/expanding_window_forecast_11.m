%% ---------------------------------------------------------
% Rolling RMSE
% ----------------------------------------------------------

rollingWindow = 8;

RollingFixedRMSE = ...
    NaN(numForecasts,1);

RollingExpandingRMSE = ...
    NaN(numForecasts,1);

RollingNaiveRMSE = ...
    NaN(numForecasts,1);

for i = rollingWindow:numForecasts

    idx = ...
        (i-rollingWindow+1):i;

    RollingFixedRMSE(i) = ...
        sqrt(mean(FixedError(idx).^2));

    RollingExpandingRMSE(i) = ...
        sqrt(mean(ExpandingError(idx).^2));

    RollingNaiveRMSE(i) = ...
        sqrt(mean(NaiveError(idx).^2));

end


%% MATLAB MACROECONOMETRICS PROJECT
% Phase 11 - Expanding Window Forecasting
%
% Objective:
% Re-estimate the forecasting model every quarter using
% all information available up to that point.
%
% Compare:
% 1. Fixed historical model
% 2. Expanding-window adaptive model
% 3. Naive persistence benchmark

disp("==============================================");
disp(" MATLAB MACROECONOMETRICS PROJECT");
disp(" Phase 11: Expanding Window Forecasting");
disp("==============================================");

%% Load cleaned quarterly dataset

DATA = readtimetable( ...
    fullfile("data","Macroeconomic_Data_Quarterly.csv"));

disp("Quarterly dataset loaded successfully.");

%% ---------------------------------------------------------
% Build forecast-ready lagged dataset
% ----------------------------------------------------------

maxLag = 4;

GDP   = DATA.GDPGrowth;
INF   = DATA.Inflation;
UNEMP = DATA.Unemployment;
RATE  = DATA.InterestRate;
DATES = DATA.observation_date;

%% Response variable

Y = GDP(maxLag+1:end);
forecastDates = DATES(maxLag+1:end);

%% Lagged GDP growth

GDP_L1 = GDP(maxLag:end-1);

%% Inflation lags

INF_L1 = INF(maxLag:end-1);
INF_L2 = INF(maxLag-1:end-2);
INF_L3 = INF(maxLag-2:end-3);
INF_L4 = INF(maxLag-3:end-4);

%% Unemployment lags

UNEMP_L1 = UNEMP(maxLag:end-1);
UNEMP_L2 = UNEMP(maxLag-1:end-2);
UNEMP_L3 = UNEMP(maxLag-2:end-3);
UNEMP_L4 = UNEMP(maxLag-3:end-4);

%% Interest-rate lags

RATE_L1 = RATE(maxLag:end-1);
RATE_L2 = RATE(maxLag-1:end-2);
RATE_L3 = RATE(maxLag-2:end-3);
RATE_L4 = RATE(maxLag-3:end-4);

%% Predictor matrix

X = [ ...
    ones(length(Y),1), ...
    GDP_L1, ...
    INF_L1, INF_L2, INF_L3, INF_L4, ...
    UNEMP_L1, UNEMP_L2, UNEMP_L3, UNEMP_L4, ...
    RATE_L1, RATE_L2, RATE_L3, RATE_L4];

%% ---------------------------------------------------------
% Define out-of-sample test period
% ----------------------------------------------------------

splitDate = datetime(2016,1,1);

trainInitial = forecastDates < splitDate;
testIndex = forecastDates >= splitDate;

testRows = find(testIndex);

Y_test = Y(testIndex);
datesTest = forecastDates(testIndex);

numForecasts = length(Y_test);

fprintf("\nInitial training observations: %d\n",sum(trainInitial));
fprintf("Out-of-sample forecasts: %d\n",numForecasts);

%% ---------------------------------------------------------
% FIXED MODEL
% Estimate once using data before 2016
% ----------------------------------------------------------

X_initial = X(trainInitial,:);
Y_initial = Y(trainInitial);

betaFixed = X_initial \ Y_initial;

FixedForecast = X(testIndex,:) * betaFixed;

%% ---------------------------------------------------------
% EXPANDING WINDOW MODEL
% Re-estimate model before every forecast
% ----------------------------------------------------------

ExpandingForecast = zeros(numForecasts,1);

CoefficientHistory = zeros( ...
    numForecasts, ...
    size(X,2));

TrainingSize = zeros(numForecasts,1);

for i = 1:numForecasts

    currentRow = testRows(i);

    % Use all observations strictly before forecast quarter
    trainingRows = 1:(currentRow-1);

    X_train = X(trainingRows,:);
    Y_train = Y(trainingRows);

    % Re-estimate coefficients
    betaAdaptive = X_train \ Y_train;

    % Generate one-step-ahead prediction
    ExpandingForecast(i) = ...
        X(currentRow,:) * betaAdaptive;

    % Save coefficient history
    CoefficientHistory(i,:) = betaAdaptive';

    TrainingSize(i) = length(Y_train);

end

%% ---------------------------------------------------------
% NAIVE BENCHMARK
% Previous quarter's GDP growth
% ----------------------------------------------------------

NaiveForecast = GDP_L1(testIndex);

%% ---------------------------------------------------------
% Forecast errors
% ----------------------------------------------------------

FixedError = Y_test - FixedForecast;

ExpandingError = ...
    Y_test - ExpandingForecast;

NaiveError = Y_test - NaiveForecast;

%% ---------------------------------------------------------
% Performance metrics
% ----------------------------------------------------------

FixedRMSE = ...
    sqrt(mean(FixedError.^2));

ExpandingRMSE = ...
    sqrt(mean(ExpandingError.^2));

NaiveRMSE = ...
    sqrt(mean(NaiveError.^2));

FixedMAE = ...
    mean(abs(FixedError));

ExpandingMAE = ...
    mean(abs(ExpandingError));

NaiveMAE = ...
    mean(abs(NaiveError));

%% Forecast correlation

FixedCorrelation = ...
    corr(Y_test,FixedForecast);

ExpandingCorrelation = ...
    corr(Y_test,ExpandingForecast);

NaiveCorrelation = ...
    corr(Y_test,NaiveForecast);

%% Directional accuracy

ActualDirection = sign(Y_test);

FixedDirectionalAccuracy = ...
    mean(sign(FixedForecast) == ...
    ActualDirection) * 100;

ExpandingDirectionalAccuracy = ...
    mean(sign(ExpandingForecast) == ...
    ActualDirection) * 100;

NaiveDirectionalAccuracy = ...
    mean(sign(NaiveForecast) == ...
    ActualDirection) * 100;

%% Improvement against naive benchmark

FixedRMSEImprovement = ...
    ((NaiveRMSE-FixedRMSE) / ...
    NaiveRMSE) * 100;

ExpandingRMSEImprovement = ...
    ((NaiveRMSE-ExpandingRMSE) / ...
    NaiveRMSE) * 100;

FixedMAEImprovement = ...
    ((NaiveMAE-FixedMAE) / ...
    NaiveMAE) * 100;

ExpandingMAEImprovement = ...
    ((NaiveMAE-ExpandingMAE) / ...
    NaiveMAE) * 100;

%% ---------------------------------------------------------
% Performance leaderboard
% ----------------------------------------------------------

Model = [ ...
    "Fixed Historical Model"
    "Expanding Window Model"
    "Naive Persistence"
    ];

RMSE = [ ...
    FixedRMSE
    ExpandingRMSE
    NaiveRMSE
    ];

MAE = [ ...
    FixedMAE
    ExpandingMAE
    NaiveMAE
    ];

Correlation = [ ...
    FixedCorrelation
    ExpandingCorrelation
    NaiveCorrelation
    ];

DirectionalAccuracy = [ ...
    FixedDirectionalAccuracy
    ExpandingDirectionalAccuracy
    NaiveDirectionalAccuracy
    ];

MODEL_LEADERBOARD = table( ...
    Model, ...
    RMSE, ...
    MAE, ...
    Correlation, ...
    DirectionalAccuracy);

disp(" ");
disp("==============================================");
disp(" EXPANDING WINDOW MODEL LEADERBOARD");
disp("==============================================");

disp(MODEL_LEADERBOARD);

fprintf("\nFixed RMSE Improvement vs Naive: %.2f %%\n", ...
    FixedRMSEImprovement);

fprintf("Expanding RMSE Improvement vs Naive: %.2f %%\n", ...
    ExpandingRMSEImprovement);

fprintf("\nFixed MAE Improvement vs Naive: %.2f %%\n", ...
    FixedMAEImprovement);

fprintf("Expanding MAE Improvement vs Naive: %.2f %%\n", ...
    ExpandingMAEImprovement);


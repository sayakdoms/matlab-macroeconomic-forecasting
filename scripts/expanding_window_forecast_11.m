%% ---------------------------------------------------------
% Coefficient history
% ----------------------------------------------------------

VariableNames = { ...
    'Intercept', ...
    'GDPGrowth_L1', ...
    'Inflation_L1', ...
    'Inflation_L2', ...
    'Inflation_L3', ...
    'Inflation_L4', ...
    'Unemployment_L1', ...
    'Unemployment_L2', ...
    'Unemployment_L3', ...
    'Unemployment_L4', ...
    'InterestRate_L1', ...
    'InterestRate_L2', ...
    'InterestRate_L3', ...
    'InterestRate_L4'};

COEFFICIENT_HISTORY = array2table( ...
    CoefficientHistory, ...
    'VariableNames', ...
    VariableNames);

COEFFICIENT_HISTORY.Date = datesTest;

COEFFICIENT_HISTORY = ...
